"""Small graphical setup for the minimum provider environment.

The optional Qt dependency is imported and installed only when ``uag setup`` is
actually invoked. The normal CLI and GUI startup paths do not import this module.
"""

from __future__ import annotations

import os
import sys
from pathlib import Path
from typing import Mapping

from uag_envsec import DEFAULT_SEC_SUFFIX, decrypt_text, ensure_key_file

from .envsec_util import encrypt_env_document
from .setup_cli import PROVIDERS, PROVIDER_FIELDS


def build_minimal_config(
    provider: str,
    field_values: Mapping[str, str],
    existing_values: Mapping[str, str] | None = None,
) -> dict[str, str]:
    """Keep non-provider settings and only the selected provider's fields."""
    if provider not in PROVIDER_FIELDS:
        raise ValueError(f"Unknown provider: {provider}")

    all_provider_keys = {
        key for fields in PROVIDER_FIELDS.values() for key, _required, _label in fields
    }
    result = {
        key: str(value)
        for key, value in (existing_values or {}).items()
        if key != "UAGENT_PROVIDER" and key not in all_provider_keys
    }
    result["UAGENT_PROVIDER"] = provider

    missing: list[str] = []
    for key, required, _label in PROVIDER_FIELDS[provider]:
        value = str(field_values.get(key, "")).strip()
        if required and not value:
            missing.append(key)
        elif value:
            result[key] = value

    if missing:
        raise ValueError("Required values are missing: " + ", ".join(missing))
    return result


def _parse_env_text(text: str) -> dict[str, str]:
    result: dict[str, str] = {}
    for line in text.splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        key = key.strip()
        if key:
            # Match the startup env reader's simple outer-quote behavior.
            value = value.strip()
            if len(value) > 1 and value[0] == value[-1] and value[0] in "\"'":
                value = value[1:-1]
            result[key] = value
    return result


def load_saved_config(directory: Path) -> dict[str, str]:
    """Load existing .env and .env.sec values; encrypted-file errors fail closed."""
    result: dict[str, str] = {}
    env_path = directory / ".env"
    sec_path = directory / f".env{DEFAULT_SEC_SUFFIX}"
    if env_path.is_file():
        result.update(_parse_env_text(env_path.read_text(encoding="utf-8")))
    if sec_path.is_file():
        encrypted = sec_path.read_text(encoding="utf-8").strip()
        result.update(_parse_env_text(decrypt_text(encrypted)))
    return result


def serialize_config(config: Mapping[str, str]) -> str:
    lines = [
        "# Minimal UAG provider configuration (generated by `uag setup`).",
        "# Keep this file private; it may contain API credentials.",
        "",
    ]
    for key in sorted(config):
        value = str(config[key])
        if "\n" in value or "\r" in value:
            raise ValueError(f"Environment values must be a single line: {key}")
        lines.append(f"{key}={value}")
    return "\n".join(lines).rstrip() + "\n"


def save_config(directory: Path, config: Mapping[str, str], *, encrypted: bool) -> Path:
    """Write the selected env format atomically and return its path."""
    directory.mkdir(parents=True, exist_ok=True)
    text = serialize_config(config)
    if encrypted:
        ensure_key_file()
        payload = encrypt_env_document(text)
        target = directory / f".env{DEFAULT_SEC_SUFFIX}"
    else:
        payload = text
        target = directory / ".env"

    temp_path = target.with_name(target.name + ".tmp")
    try:
        temp_path.write_text(payload, encoding="utf-8", newline="\n")
        if not encrypted and os.name != "nt":
            temp_path.chmod(0o600)
        temp_path.replace(target)
    finally:
        try:
            temp_path.unlink(missing_ok=True)
        except OSError:
            pass
    return target


def main() -> int:
    """Run the PySide6 setup dialog, installing PySide6 on demand if needed."""
    from ._pip_auto import install_with_status

    if not install_with_status(
        "PySide6",
        "PySide6",
        display_name="PySide6 GUI support",
        verify_submodule="PySide6.QtCore",
    ):
        return 1

    from PySide6.QtCore import Qt
    from PySide6.QtWidgets import (
        QApplication,
        QCheckBox,
        QComboBox,
        QDialog,
        QDialogButtonBox,
        QFormLayout,
        QHBoxLayout,
        QLabel,
        QLineEdit,
        QMessageBox,
        QScrollArea,
        QVBoxLayout,
        QWidget,
    )

    app = QApplication.instance() or QApplication(sys.argv[:1])
    app.setApplicationName("UAG Setup")
    directory = Path.cwd().resolve()
    try:
        saved_values = load_saved_config(directory)
    except Exception as exc:
        QMessageBox.critical(
            None,
            "UAG Setup",
            "既存の設定を読み込めませんでした。暗号化キーや .env.sec を確認してください。\n\n"
            f"{exc}",
        )
        return 1

    defaults = dict(saved_values)
    # Process environment values can prefill provider fields, but unrelated
    # process variables are never copied into the saved configuration.
    defaults.update(
        {key: value for key, value in os.environ.items() if key.startswith("UAGENT_")}
    )
    provider_default = defaults.get("UAGENT_PROVIDER", "openai").lower()
    if provider_default not in PROVIDER_FIELDS:
        provider_default = "openai"

    class SetupDialog(QDialog):
        def __init__(self) -> None:
            super().__init__()
            self.setWindowTitle("UAG セットアップ / UAG Setup")
            self.setMinimumSize(560, 500)
            self.directory = directory
            self.saved_values = saved_values
            self.values = dict(defaults)
            self.editors: dict[str, QLineEdit] = {}

            root = QVBoxLayout(self)
            intro = QLabel(
                "利用するプロバイダーと必要な値を設定します。\n"
                "必須項目だけで開始でき、任意項目は必要な場合に表示できます。"
            )
            intro.setWordWrap(True)
            root.addWidget(intro)

            location = QLabel(f"保存先: {directory}")
            location.setTextInteractionFlags(
                Qt.TextInteractionFlag.TextSelectableByMouse
            )
            root.addWidget(location)

            provider_row = QHBoxLayout()
            provider_row.addWidget(QLabel("プロバイダー:"))
            self.provider = QComboBox()
            for key, label in PROVIDERS:
                self.provider.addItem(f"{label} ({key})", key)
            provider_row.addWidget(self.provider, 1)
            root.addLayout(provider_row)

            self.show_optional = QCheckBox("任意の環境変数も表示")
            root.addWidget(self.show_optional)

            scroll = QScrollArea()
            scroll.setWidgetResizable(True)
            self.form_widget = QWidget()
            self.form = QFormLayout(self.form_widget)
            self.form.setFieldGrowthPolicy(
                QFormLayout.FieldGrowthPolicy.ExpandingFieldsGrow
            )
            scroll.setWidget(self.form_widget)
            root.addWidget(scroll, 1)

            self.encrypt = QCheckBox("暗号化して .env.sec に保存（推奨）")
            self.encrypt.setChecked(True)
            root.addWidget(self.encrypt)
            self.warning = QLabel(
                "暗号化を外すと、APIキーが平文の .env に保存されます。"
            )
            self.warning.setWordWrap(True)
            root.addWidget(self.warning)

            buttons = QDialogButtonBox(
                QDialogButtonBox.StandardButton.Save
                | QDialogButtonBox.StandardButton.Cancel
            )
            buttons.accepted.connect(self.save)
            buttons.rejected.connect(self.reject)
            root.addWidget(buttons)

            idx = self.provider.findData(provider_default)
            self.provider.setCurrentIndex(max(0, idx))
            self.provider.currentIndexChanged.connect(self.provider_changed)
            self.show_optional.toggled.connect(self.optional_changed)
            self.provider_changed()

        def _selected_provider(self) -> str:
            return str(self.provider.currentData())

        def _capture_fields(self) -> None:
            for key, editor in self.editors.items():
                self.values[key] = editor.text()

        def _clear_form(self) -> None:
            while self.form.count():
                item = self.form.takeAt(0)
                widget = item.widget()
                if widget is not None:
                    widget.deleteLater()
            self.editors.clear()

        def _render_fields(self) -> None:
            self._clear_form()
            provider = self._selected_provider()
            fields = PROVIDER_FIELDS[provider]
            for key, required, label in fields:
                if not required and not self.show_optional.isChecked():
                    continue
                editor = QLineEdit(str(self.values.get(key, "")))
                editor.setPlaceholderText("必須" if required else "任意")
                if any(
                    token in key
                    for token in ("API_KEY", "TOKEN", "CREDENTIALS", "SECRET")
                ):
                    editor.setEchoMode(QLineEdit.EchoMode.Password)
                self.form.addRow(label + (" *" if required else ""), editor)
                self.editors[key] = editor

        def provider_changed(self, *_args) -> None:
            self._capture_fields()
            provider = self._selected_provider()
            optional_is_set = any(
                bool(self.values.get(key, "").strip())
                for key, required, _label in PROVIDER_FIELDS[provider]
                if not required
            )
            self.show_optional.blockSignals(True)
            self.show_optional.setChecked(optional_is_set)
            self.show_optional.blockSignals(False)
            self._render_fields()

        def optional_changed(self, _checked: bool) -> None:
            self._capture_fields()
            self._render_fields()

        def save(self) -> None:
            self._capture_fields()
            provider = self._selected_provider()
            fields = PROVIDER_FIELDS[provider]
            field_values = dict(self.values)
            if not self.show_optional.isChecked():
                for key, required, _label in fields:
                    if not required:
                        field_values.pop(key, None)
            try:
                config = build_minimal_config(provider, field_values, self.saved_values)
            except ValueError as exc:
                QMessageBox.warning(self, "入力を確認してください", str(exc))
                return

            encrypted = self.encrypt.isChecked()
            target_name = f".env{DEFAULT_SEC_SUFFIX}" if encrypted else ".env"
            other_name = ".env" if encrypted else f".env{DEFAULT_SEC_SUFFIX}"
            existing_paths = [
                self.directory / name
                for name in (target_name, other_name)
                if (self.directory / name).exists()
            ]
            if existing_paths:
                listed = "\n".join(str(path) for path in existing_paths)
                answer = QMessageBox.question(
                    self,
                    "既存設定の置き換え",
                    "既存の設定ファイルを統合して置き換えます。続行しますか？\n"
                    "選択したプロバイダー以外のプロバイダー設定は削除されます。\n\n"
                    f"{listed}",
                    QMessageBox.StandardButton.Yes | QMessageBox.StandardButton.No,
                    QMessageBox.StandardButton.No,
                )
                if answer != QMessageBox.StandardButton.Yes:
                    return
            try:
                target = save_config(self.directory, config, encrypted=encrypted)
                other = self.directory / other_name
                if other.exists():
                    other.unlink()
            except Exception as exc:
                QMessageBox.critical(self, "保存に失敗しました", str(exc))
                return

            QMessageBox.information(
                self,
                "保存しました",
                f"必要な設定を保存しました。\n{target}\n\n"
                "設定を反映するには、UAGを再起動してください。",
            )
            self.accept()

    dialog = SetupDialog()
    return 0 if dialog.exec() == QDialog.DialogCode.Accepted else 1


if __name__ == "__main__":
    raise SystemExit(main())
